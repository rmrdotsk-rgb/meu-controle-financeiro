-- Estrutura da versão anterior. Bancos existentes recebem baseline na versão 1.
CREATE TABLE despesas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria VARCHAR(30) NOT NULL,
    data DATE NOT NULL,
    descricao VARCHAR(120) NOT NULL,
    valor NUMERIC(12,2) NOT NULL
);
CREATE TABLE receitas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria VARCHAR(30) NOT NULL,
    data DATE NOT NULL,
    descricao VARCHAR(120) NOT NULL,
    valor NUMERIC(12,2) NOT NULL
);
CREATE TABLE metas_financeiras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_limite DATE NOT NULL,
    nome VARCHAR(80) NOT NULL,
    valor_alvo NUMERIC(12,2) NOT NULL
);
CREATE TABLE aportes_metas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data DATE NOT NULL,
    valor NUMERIC(12,2) NOT NULL,
    meta_id BIGINT NOT NULL,
    CONSTRAINT fk_aporte_meta FOREIGN KEY (meta_id) REFERENCES metas_financeiras(id)
);
CREATE TABLE orcamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria VARCHAR(30) NOT NULL,
    limite NUMERIC(12,2) NOT NULL,
    mes VARCHAR(7) NOT NULL,
    CONSTRAINT uk_orcamento_mes_categoria UNIQUE(mes,categoria)
);
