CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    demonstracao BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT uk_usuario_email UNIQUE(email)
);

-- O vínculo é deliberadamente anulável para preservar registros antigos em quarentena.
-- Nenhuma conta nova recebe esses dados. Toda consulta da aplicação exige proprietário.
ALTER TABLE despesas ADD COLUMN usuario_id BIGINT;
ALTER TABLE receitas ADD COLUMN usuario_id BIGINT;
ALTER TABLE metas_financeiras ADD COLUMN usuario_id BIGINT;
ALTER TABLE orcamentos ADD COLUMN usuario_id BIGINT;
ALTER TABLE despesas ADD CONSTRAINT fk_despesa_usuario FOREIGN KEY(usuario_id) REFERENCES usuarios(id);
ALTER TABLE receitas ADD CONSTRAINT fk_receita_usuario FOREIGN KEY(usuario_id) REFERENCES usuarios(id);
ALTER TABLE metas_financeiras ADD CONSTRAINT fk_meta_usuario FOREIGN KEY(usuario_id) REFERENCES usuarios(id);
ALTER TABLE orcamentos ADD CONSTRAINT fk_orcamento_usuario FOREIGN KEY(usuario_id) REFERENCES usuarios(id);

-- Substitui somente a restrição global; nenhuma tabela, linha ou dado é removido.
